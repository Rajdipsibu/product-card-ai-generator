interface ProductDetails{
  title:string;
  description:string;
  keywords:string[];
}

interface GeminiResponse{
  candidates?:{
    content?:{
      parts?:{
        text?:string;
      }[];
    };
  }[];
}

export async function generateProductDetails(
  productName:string,
  category:string,
):Promise<ProductDetails> {
  const apikey = process.env.GEMINI_API_KEY;
  if(!apikey){
    throw new Error("Gemini API Key is not configured");
  }

  const prompt = `
    You are a expert e-commerce copywriter.

    Generate product card details for:
    Product name:${productName}
    Category:${category}

    Return ONLY a valid JSON object in this format:
    {
      "title": "A clear, attractive product title",
      "description" "A concise product description under 40 words",
      "keywords": ["keyword1","keyword2","keyword3","keyword4","keyword5"]
    }

    Rules:
    - Keep the title concise and relevant.
    - Do not invent specifications or certifications.
    - Do not use Markdown or code fences.
    - Return exactly five relevent keywords.
  `;

  const response = await fetch(
    "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent",
    {
      method:"POST",
      headers: {
        "Content-Type": "application/json",
        "x-goog-api-key":apikey
      },
      body:JSON.stringify({
        contents:[
          {
            parts: [{text: prompt}]
          }
        ],
        generationConfig:{
          responseMimeType:"application/json",
          maxOutputTokens: 300
        }
      }),
      signal: AbortSignal.timeout(30000)
    }
  );

  if(!response.ok){
    const errorBody = await response.text();
    console.error("Gemini API Error:", errorBody);
    throw new Error(`Gemini API request failed with status ${response.status}`);
  }

  const data = (await response.json()) as GeminiResponse;
  const generatedText = data.candidates?.[0]?.content?.parts?.map((part)=>part.text??"").join("").trim();

  if(!generatedText){
    throw new Error("No content generated by Gemini API");
  }

  const result = JSON.parse(generatedText) as Partial<ProductDetails>;

  if(
    typeof result.title !== "string" ||
    typeof result.description !== "string" ||
    !Array.isArray(result.keywords) ||
    result.keywords.length !== 5 ||
    !result.keywords.every((kw) => typeof kw === "string")
  ){
    throw new Error("Generated content is not in the expected format");
  }

  return {
    title: result.title,
    description: result.description,
    keywords: result.keywords
  }

}