interface ProductDetails {
  title: string;
  description: string;
  keywords: string[];
}

interface GeminiResponse {
  candidates?: {
    content?: {
      parts?: {
        text?: string;
      }[];
    };
  }[];
}

export async function generateProductDetails(
  productName: string,
  category: string
): Promise<ProductDetails> {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey) {
    throw new Error("Gemini API key is not configured");
  }

  const prompt = `
    You are an expert e-commerce copywriter.

    Product name: ${productName}
    Category: ${category}

    Return only a valid JSON object:
    {
      "title": "A clear, attractive product title",
      "description": "A concise product description under 40 words",
      "keywords": [
        "keyword1",
        "keyword2",
        "keyword3",
        "keyword4",
        "keyword5"
      ]
    }

    Rules:
    - Keep the title concise and relevant.
    - Do not invent product specifications or certifications.
    - Return exactly five relevant keywords.
    - Return JSON only, without Markdown.
  `;

  const response = await fetch(
    "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent",
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-goog-api-key": apiKey,
      },
      body: JSON.stringify({
        contents: [
          {
            parts: [{ text: prompt }],
          },
        ],
        generationConfig: {
          responseMimeType: "application/json",
          maxOutputTokens: 300,
        },
      }),
      signal: AbortSignal.timeout(30000),
    }
  );

  if (!response.ok) {
    const errorBody = await response.text();
    console.error("Gemini API error:", errorBody);
    throw new Error(
      `Gemini API request failed with status ${response.status}`
    );
  }

  const data = (await response.json()) as GeminiResponse;

  const generatedText = data.candidates?.[0]?.content?.parts
    ?.map((part) => part.text ?? "")
    .join("")
    .trim();

  if (!generatedText) {
    throw new Error("No content generated by Gemini AI");
  }

  let result: Partial<ProductDetails>;

  try {
    result = JSON.parse(generatedText) as Partial<ProductDetails>;
  } catch {
    throw new Error("Gemini returned invalid JSON");
  }

  if (
    typeof result.title !== "string" ||
    typeof result.description !== "string" ||
    !Array.isArray(result.keywords) ||
    result.keywords.length !== 5 ||
    !result.keywords.every(
      (keyword) => typeof keyword === "string"
    )
  ) {
    throw new Error("Generated content has an invalid format");
  }

  return {
    title: result.title,
    description: result.description,
    keywords: result.keywords,
  };
}
